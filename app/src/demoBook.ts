const TITLES = ['Смотритель маяка', '1. Остров', '2. Журнал', '3. Туман', 'Примечания'];

export function demoBookView(): BookView {
  const chapters = CHAPTERS.map((c, i) => ({ title: TITLES[i], size: [...textOf(c)].length }));
  return {
    hash: DEMO_BOOK,
    format: 'fb2',
    meta: { title: 'Смотритель маяка', authors: ['Полка'], lang: 'ru', genres: ['Рассказ'] },
    chapters,
    toc: TITLES.slice(1).map((title, i) => ({ title, chapter: i + 1, depth: 0 })),
    total: chapters.reduce((a, c) => a + c.size, 0),
    title: null,
  };
}

export function demoChapter(i: number): BookNode[] {
  const c = CHAPTERS[i];
  if (!c) throw new Error('нет такой главы');
  return JSON.parse(JSON.stringify(c));
}

/** Поиск по демо-книге — как в ядре: без регистра и разницы «е» и «ё». */
export function demoSearch(query: string) {
  const fold = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/ /g, ' ');
  const q = fold(query.trim().replace(/\s+/g, ' '));
  const hits: { chapter: number; offset: number; len: number; before: string; found: string; after: string }[] = [];
  if (q.length < 2) return hits;
  CHAPTERS.forEach((c, chapter) => {
    const text = textOf(c);
    const low = fold(text);
    for (let at = low.indexOf(q); at >= 0; at = low.indexOf(q, at + q.length)) {
      hits.push({ chapter, offset: at, len: q.length, before: text.slice(Math.max(0, at - 40), at), found: text.slice(at, at + q.length), after: text.slice(at + q.length, at + q.length + 60) });
    }
  });
  return hits;
}

